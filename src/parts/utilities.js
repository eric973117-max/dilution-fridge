import * as THREE from '../../vendor/three.module.js';

/* ------------------------------------------------------------- utilities */

export function rng(seed = 1) {
  let s = seed >>> 0;
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };
}

export const V = (x, y, z) => new THREE.Vector3(x, y, z);
