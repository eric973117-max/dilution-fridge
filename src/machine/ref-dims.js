/* ==========================================================================
   ref-dims · 唯一尺寸来源

   全部由参考立面图（Feature-Image-Illustration-New）逐像素量出来，
   再用「整机总高 = 1.77 m」换算成米。以后所有几何只准引用这里，
   不许在各个 segNN 里再写裸数字。

   量法：图幅 950×950，机器内容包围盒 x 188..588、y 117..832，
        总高 716 px、最大宽 400 px（顶法兰）→ 宽高比 0.559。
        每一行取非黑像素的左右边界，得到宽度剖面，
        再把「宽/总高」乘回总高，就是那一层的真实直径。

   t  = 从机头顶部往下归一化的高度（0 = 顶，1 = 底）
   y  = 世界坐标，0 定在整机高度中点
   ========================================================================== */

/* 总高按「盘径 ÷ 量到的机身宽高比」反推：
   大盘 Ø0.72 m（大型稀释制冷机的实际量级）÷ 0.383（参考图量到的 w/h）= 1.88 m */
export const TOTAL_H = 1.88;

/* --- 已确认的整机构成（用户拍板） --- */
export const POST_COUNT = 6;      // 六根立柱（立在盘面上，不在盘外）
export const BOX_COUNT = 6;       // 底部六个方箱，环形均布
export const HAS_CAN = false;     // 不要真空筒 —— 裸机

/* --- 立柱与方箱的参数（用户拍板） --- */
export const POST = {
  r: 0.285,        // 立柱所在的半径：落在焊盘圈和外圈减重孔之间，站在盘面上
  holeR: 0.016,    // 盘上给立柱留的过孔
  section: 0.030,
  collarR: 0.025,
  collarH: 0.026,
};

export const BOX = {
  /* 实测：竖向立着的扁盒，高 > 宽 > 厚，薄的那面朝外 */
  w: 0.100, h: 0.160, d: 0.055,
  ringR: 0.220,                   // 环形排布半径
  rows: 6,                        // 每侧一排端子（共两排）
  wires: 12,                      // 端子总数 = rows × 2
};
export const AT = (t) => (0.5 - t) * TOTAL_H;   // 归一化高度 → 世界 y
export const W2R = (w) => (w * TOTAL_H) / 2;    // 归一化宽度 → 半径

/* --- 参考图量到的关键水平线（归一化高度 t 与归一化宽度 w） --- */
export const MEASURED = {
  headBlock: { t0: 0.000, t1: 0.062, w: 0.490 },   // 顶部机头（脉冲管机头）
  topFlange: { t: 0.084, w: 0.559 },               // 顶法兰——整机最宽
  bodyW: 0.383,                                    // 机身（盘径）标准宽度
  ringW: 0.470,                                    // 幕中环圈那一级的宽度
  plateT: [0.100, 0.250, 0.440, 0.620, 0.800],     // 五块盘
  ringT: [0.186, 0.346, 0.472, 0.615, 0.736],      // 五处环圈/线圈
  bottomT0: 0.800,                                 // 底部组件起
  bottomT1: 0.950,                                 // 底部组件止
  bottomW0: 0.341,                                 // 底部起点宽度
  bottomW1: 0.270,                                 // 底部终点宽度
  tipW: 0.071,                                     // 最末端的细端
};

/* --- 由此推出的尺寸（米） --- */
export const RD = {
  totalH: TOTAL_H,
  head: { yTop: AT(0.000), yBot: AT(0.062), r: W2R(0.490) },
  flange: { y: AT(0.084), r: W2R(0.559) },
  body: { r: W2R(0.383) },
  ring: { r: W2R(0.470) },
  ground: AT(1.000),
  bottom: { yTop: AT(0.800), yBot: AT(0.950), rTop: W2R(0.341), rBot: W2R(0.270) },
};

/** 五块盘：位置 + 半径（半径按量到的盘宽） */
export const RD_PLATES = MEASURED.plateT.map((t, i) => ({
  key: `p${i + 1}`,
  y: AT(t),
  /* 五块冷盘尺寸不一样：从上往下逐级收，实物照片里最下面那块明显最小 */
  r: [0.415, 0.398, 0.375, 0.345, 0.308][i],
  ringR: W2R(MEASURED.ringW),
}));

/** 五处环圈层：位置（半径用 ringR） */
export const RD_RINGS = MEASURED.ringT.map((t) => ({ y: AT(t), r: W2R(MEASURED.ringW) }));
